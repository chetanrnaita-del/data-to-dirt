"""Deep Content Inspector for FileClean.

Inspects the actual contents of files on-device to determine whether a file is:
- An auto-generated log, crash dump, or stack trace
- An empty, skeleton, or placeholder stub (e.g., 'test', lorem ipsum)
- An obsolete scratch/draft file vs meaningful personal work
- A duplicate or near-duplicate draft of a sibling document
- Sensitive/valuable user work (source code, receipts, personal notes)

Runs 100% locally with strict size and memory safeguards.
"""

from __future__ import annotations

import os
import re
import difflib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional, List, Tuple

# Patterns identifying auto-generated / machine-generated files
AUTO_GEN_PATTERNS = [
    re.compile(r"automatically generated", re.IGNORECASE),
    re.compile(r"do not edit", re.IGNORECASE),
    re.compile(r"generated by", re.IGNORECASE),
    re.compile(r"autogenerated", re.IGNORECASE),
    re.compile(r"build artifact", re.IGNORECASE),
    re.compile(r"stack trace:", re.IGNORECASE),
    re.compile(r"traceback \(most recent call last\):", re.IGNORECASE),
    re.compile(r"npm err!", re.IGNORECASE),
    re.compile(r"exception in thread", re.IGNORECASE),
    re.compile(r"fatal error", re.IGNORECASE),
    re.compile(r"dumped from database", re.IGNORECASE),
]

# Patterns identifying placeholder / stub content
PLACEHOLDER_PATTERNS = [
    re.compile(r"lorem ipsum", re.IGNORECASE),
    re.compile(r"todo:?\s*fill this in", re.IGNORECASE),
    re.compile(r"^#\s*untitled\s*$", re.IGNORECASE | re.MULTILINE),
    re.compile(r"hello world", re.IGNORECASE),
    re.compile(r"test content", re.IGNORECASE),
    re.compile(r"asdf+", re.IGNORECASE),
]

# Patterns identifying substantive personal/valuable documents
VALUABLE_SIGNALS = [
    re.compile(r"\b(agreement|contract|invoice|receipt|tax|statement|resume|cv)\b", re.IGNORECASE),
    re.compile(r"\b(confidential|private|dear|sincerely|regards)\b", re.IGNORECASE),
    re.compile(r"\b(password|secret|key|token|credentials)\b", re.IGNORECASE),  # Protect secrets from ever being deleted!
    re.compile(r"\b(budget|balance|revenue|expenses|payroll)\b", re.IGNORECASE),
]


@dataclass
class ContentAnalysisResult:
    """Findings from looking inside a file."""
    path: Path
    is_readable: bool = False
    is_binary: bool = False
    size_bytes: int = 0
    lines_count: int = 0
    words_count: int = 0
    is_empty: bool = False
    is_placeholder: bool = False
    is_auto_generated: bool = False
    contains_valuable_signals: bool = False
    content_summary: str = ""
    extracted_snippet: str = ""
    disposable_confidence: float = 0.0  # 0.0 = definitely keep, 1.0 = definitely disposable
    disposable_reasons: List[str] = field(default_factory=list)

    @property
    def is_safe_to_recommend(self) -> bool:
        """Only recommend if we have confirmed evidence it's disposable and not valuable."""
        if self.contains_valuable_signals:
            return False
        return self.disposable_confidence >= 0.70


class ContentInspector:
    """Inspects file contents locally to ground recommendations in real data."""

    def __init__(self, max_read_bytes: int = 64 * 1024):
        self.max_read_bytes = max_read_bytes

    def inspect(self, file_path: Path) -> ContentAnalysisResult:
        """Deeply inspect a file's content and evaluate its true necessity."""
        result = ContentAnalysisResult(path=file_path)

        if not file_path.exists() or not file_path.is_file():
            return result

        try:
            stat = file_path.stat()
            result.size_bytes = stat.st_size
        except OSError:
            return result

        # 0-byte file check
        if result.size_bytes == 0:
            result.is_empty = True
            result.disposable_confidence = 0.95
            result.disposable_reasons.append("File is completely empty (0 bytes)")
            result.content_summary = "Empty file"
            return result

        # Check binary vs text
        try:
            with open(file_path, "rb") as f:
                raw_header = f.read(1024)
        except (PermissionError, OSError):
            return result

        if b"\0" in raw_header:
            result.is_binary = True
            # Binary files: identify known formats or safe dumps
            return self._inspect_binary(file_path, raw_header, result)

        # Text-based file inspection
        return self._inspect_text(file_path, result)

    def _inspect_text(self, file_path: Path, result: ContentAnalysisResult) -> ContentAnalysisResult:
        """Inspect plain text, markdown, source code, config, logs."""
        try:
            with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                content = f.read(self.max_read_bytes)
        except Exception:
            return result

        result.is_readable = True
        stripped = content.strip()

        if not stripped:
            result.is_empty = True
            result.disposable_confidence = 0.95
            result.disposable_reasons.append("File contains only whitespace")
            result.content_summary = "Empty whitespace file"
            return result

        lines = stripped.splitlines()
        result.lines_count = len(lines)
        words = stripped.split()
        result.words_count = len(words)
        result.extracted_snippet = " ".join(words[:40])

        # 1. Check for valuable personal signals (contracts, tax, keys, credentials)
        for pattern in VALUABLE_SIGNALS:
            if pattern.search(content):
                result.contains_valuable_signals = True
                result.disposable_confidence = 0.05
                result.disposable_reasons.clear()
                result.content_summary = "Important personal/financial or sensitive document"
                return result

        # 2. Check for auto-generated / crash dumps / log files
        auto_gen_hits = []
        for pattern in AUTO_GEN_PATTERNS:
            match = pattern.search(content[:4096])
            if match:
                auto_gen_hits.append(match.group(0))

        if auto_gen_hits:
            result.is_auto_generated = True
            result.disposable_confidence = 0.90
            result.disposable_reasons.append(f"Auto-generated output/log: '{auto_gen_hits[0]}'")
            result.content_summary = f"Machine-generated data ({auto_gen_hits[0]})"
            return result

        # 3. Check for placeholder / dummy text
        placeholder_hits = []
        for pattern in PLACEHOLDER_PATTERNS:
            match = pattern.search(content[:2048])
            if match:
                placeholder_hits.append(match.group(0))

        if placeholder_hits:
            result.is_placeholder = True
            result.disposable_confidence = 0.85
            result.disposable_reasons.append(f"Placeholder/dummy content detected: '{placeholder_hits[0]}'")
            result.content_summary = "Placeholder / scratch template"
            return result

        # 4. Tiny scratch files (< 5 words without structure)
        if result.words_count <= 4 and result.lines_count <= 2:
            result.disposable_confidence = 0.75
            result.disposable_reasons.append(f"Minimal scratch note ({result.words_count} words): '{result.extracted_snippet}'")
            result.content_summary = f"Tiny scratch note: '{result.extracted_snippet}'"
            return result

        # Substantive content
        result.disposable_confidence = 0.15
        result.content_summary = f"Active text document ({result.lines_count} lines, {result.words_count} words)"
        return result

    def _inspect_binary(self, file_path: Path, header: bytes, result: ContentAnalysisResult) -> ContentAnalysisResult:
        """Inspect binary files safely without crashing."""
        result.is_readable = False

        # SQLite database check
        if header.startswith(b"SQLite format 3"):
            result.content_summary = "SQLite Database file"
            result.contains_valuable_signals = True
            result.disposable_confidence = 0.10
            return result

        # PDF check
        if header.startswith(b"%PDF-"):
            result.content_summary = "PDF Document"
            # Try to extract plain text keywords from raw PDF stream safely
            if re.search(b"(?i)invoice|statement|receipt|tax|contract", header):
                result.contains_valuable_signals = True
                result.disposable_confidence = 0.05
            else:
                result.disposable_confidence = 0.20
            return result

        # macOS .DS_Store header
        if header.startswith(b"\x00\x00\x00\x01Bud1"):
            result.is_auto_generated = True
            result.disposable_confidence = 0.99
            result.disposable_reasons.append("Verified macOS Desktop Services metadata store")
            result.content_summary = "macOS folder icon/view layout cache"
            return result

        # Core / crash dumps (Mach-O core dump on macOS: 0xfeedface, 0xfeedfacf)
        if header.startswith(b"\xfe\xed\xfa\xce") or header.startswith(b"\xcf\xfa\xed\xfe"):
            result.is_auto_generated = True
            result.disposable_confidence = 0.95
            result.disposable_reasons.append("OS crash core dump")
            result.content_summary = "System crash dump"
            return result

        result.content_summary = f"Binary file ({result.size_bytes} bytes)"
        result.disposable_confidence = 0.30
        return result

    def compare_content_similarity(self, file1: Path, file2: Path) -> float:
        """Calculate content similarity ratio (0.0 to 1.0) between two text files.
        Used to detect redundant revisions/drafts even if modified slightly."""
        try:
            with open(file1, "r", encoding="utf-8", errors="ignore") as f1, \
                 open(file2, "r", encoding="utf-8", errors="ignore") as f2:
                t1 = f1.read(32 * 1024)
                t2 = f2.read(32 * 1024)
            return difflib.SequenceMatcher(None, t1, t2).quick_ratio()
        except Exception:
            return 0.0
