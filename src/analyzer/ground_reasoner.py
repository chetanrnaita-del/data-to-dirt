class GroundReasoner:
    """Dedicated filesystem and storage intelligence engine.

    Investigates real ground truth across scanned paths, extracts deep
    telemetry, probes file contents, debates tradeoffs through the Review
    Council, and synthesizes tailored, non-robotic insights with a transparent
    thought process.
    """

    def __init__(
        self,
        content_inspector: Optional[ContentInspector] = None,
        user_profile: Optional[UserProfile] = None,
        council: Optional[ReviewCouncil] = None,
    ):
        self.inspector = content_inspector or ContentInspector()
        self.profile = user_profile
        self.council = council or ReviewCouncil()

    def reason(self, query: str, scan_result: Optional[ScanResult] = None) -> GroundThinkingResult:
        """Execute a full ground-level reasoning cycle for a user inquiry."""
        start_time = time.perf_counter()
        thought_steps: list[str] = []
        inspected_files: list[str] = []

        q_lower = query.lower()

        # Step 1: Parse query intent
        intent = self._classify_intent(q_lower)
        thought_steps.append(f"Parsed inquiry intent: **{intent}** from query '{query[:60]}...'")

        # ── Direct Disk Folder Probe ───────────────────────────────
        # If user asks about a specific directory on their computer (e.g. Desktop, Downloads),
        # directly probe and report its live contents on disk.
        disk_path_match = self._find_disk_path_in_query(q_lower)
        if disk_path_match and (not scan_result or disk_path_match != scan_result.directory):
            return self._probe_disk_folder(disk_path_match, thought_steps, start_time)

        # ── General Knowledge & Safety (No Active Scan Needed) ────
        if intent in ("greeting", "capabilities", "knowledge", "privacy", "safety_assessment") or (not scan_result and intent in ("general_filesystem_query", "cleanup_strategy")):
            return self._handle_general_query(query, q_lower, intent, thought_steps, start_time)

        # If user is asking scan-specific questions (what to clean, space savings, scan issues) without a scan
        if not scan_result or not scan_result.issues:
            thought_steps.append("Inspecting active scan state: No active filesystem scan available in memory.")
            thought_steps.append("Synthesizing actionable guidance directing user to choose a scan folder.")
            duration_ms = (time.perf_counter() - start_time) * 1000
            return GroundThinkingResult(
                thought_steps=thought_steps,
                answer=(
                    "I haven't scanned a directory yet! Select a folder above (such as your **Desktop** or **Downloads**) "
                    "and click **🔍 Scan**.\n\n"
                    "Once you scan, I will investigate the real files on disk, peek inside their contents, "
                    "detect duplicate byte-twins, and formulate a step-by-step cleanup plan tailored to you."
                ),
                duration_ms=duration_ms,
            )

        # ── Active Scan Ground Analysis ────────────────────────────
        scan_dir = scan_result.directory
        issues = scan_result.issues
        total_size = sum(i.size for i in issues)

        thought_steps.append(
            f"Gathered filesystem telemetry for `{scan_dir.name}`: {len(issues)} candidate issues "
            f"representing {format_size(total_size)} reclaimable space."
        )

        clusters = self._extract_folder_clusters(issues)
        cluster_summary = ", ".join(f"'{k}' ({len(v)} files)" for k, v in list(clusters.items())[:3])
        thought_steps.append(f"Identified {len(clusters)} directory clusters: {cluster_summary or 'root directory'}.")

        # Step 3: Deep File Probing & Council Deliberation
        target_issue = self._find_target_issue(q_lower, issues)
        if target_issue:
            inspected_files.append(str(target_issue.path))
            content = self.inspector.inspect(target_issue.path)
            thought_steps.append(
                f"Probed inside candidate file `{target_issue.path.name}`: {content.content_summary} "
                f"({content.words_count} words, {content.lines_count} lines)."
            )
            if self.profile:
                is_prot, prot_reason = self.profile.evaluate_file_safety(target_issue.path)
                thought_steps.append(f"Consulted user profile rules: protected={is_prot} ({prot_reason}).")

            council_eval = self.council.evaluate_candidate(target_issue, content, self.profile or UserProfile(None))
            thought_steps.append(
                f"Multi-Agent Council Deliberation: Verdict={council_eval.verdict.value} "
                f"({council_eval.consensus_summary})"
            )

        # Step 4: Synthesize Contextual Answer
        thought_steps.append("Synthesizing context-grounded response with concrete file citations.")

        answer = self._synthesize_response(
            intent=intent,
            query=query,
            q_lower=q_lower,
            scan_result=scan_result,
            clusters=clusters,
            target_issue=target_issue,
            thought_steps=thought_steps,
        )

        duration_ms = (time.perf_counter() - start_time) * 1000
        return GroundThinkingResult(
            thought_steps=thought_steps,
            answer=answer,
            duration_ms=duration_ms,
            inspected_files=inspected_files,
        )

    def _classify_intent(self, q: str) -> str:
        if any(w in q for w in ["hello", "hi", "hey", "good morning", "greetings"]):
            return "greeting"
        if any(w in q for w in ["who are you", "what can you do", "help", "how do you work", "features", "capabilities"]):
            return "capabilities"
        if any(w in q for w in ["privacy", "offline", "upload", "cloud", "security", "safe to use", "private", "secret", "trust"]):
            return "privacy"
        if any(w in q for w in ["what is", "explain .", "tell me about .", "what does", "meaning of"]):
            return "knowledge"
        if any(w in q for w in ["what should i clean", "where to start", "first", "recommend", "advice", "what to do", "priority", "how to clean", "how do i clean"]):
            return "cleanup_strategy"
        if any(w in q for w in ["duplicate", "same file", "copies", "clones", "identical"]):
            return "duplicate_investigation"
        if any(w in q for w in ["why", "reason", "look inside", "inspect", "what is in"]):
            return "file_investigation"
        if any(w in q for w in ["safe", "danger", "risk", "can i delete", "harm", "break"]):
            return "safety_assessment"
        if any(w in q for w in ["biggest", "largest", "taking space", "most space", "heavy"]):
            return "space_consumers"
        if any(w in q for w in ["folder", "directory", "cluster", "breakdown", "tree"]):
            return "folder_breakdown"
        return "general_filesystem_query"

    def _find_disk_path_in_query(self, q: str) -> Optional[Path]:
        """Detect if user mentioned a real filesystem directory."""
        home = Path.home()
        candidates = {
            "desktop": home / "Desktop",
            "downloads": home / "Downloads",
            "documents": home / "Documents",
            "pictures": home / "Pictures",
            "movies": home / "Movies",
        }
        for name, p in candidates.items():
            if name in q and p.exists():
                return p
        return None

