def generate_dataset(num_samples: int = 4000, seed: int = 42) -> List[Dict[str, Any]]:
    """
    Generates a balanced dataset of synthetic file contexts and stated deletion justifications.
    Returns a list of dictionaries with context metadata and target label (1.0 or 0.0).
    """
    rng = random.Random(seed)

    # 50% positive (plausible) and 50% negative (gaming / threat)
    pos_target = num_samples // 2
    neg_target = num_samples - pos_target

    # Distribution among positive classes:
    # 40% cache/temp, 30% duplicates, 30% obsolete
    n_cache = int(pos_target * 0.40)
    n_dup = int(pos_target * 0.30)
    n_obs = pos_target - n_cache - n_dup

    # Distribution among negative classes:
    # 35% gibberish, 35% score farming, 30% malicious system risk
    n_gib = int(neg_target * 0.35)
    n_farm = int(neg_target * 0.35)
    n_sys = neg_target - n_gib - n_farm

    dataset: List[Dict[str, Any]] = []

    def sample_from_templates(templates, count, category, label):
        for i in range(count):
            tpl_name, ext, (min_size, max_size), (min_age, max_age), reasons = rng.choice(templates)
            filename = tpl_name.format(i=rng.randint(1, 9999))
            size = rng.randint(int(min_size), int(max_size))
            age = round(rng.uniform(min_age, max_age), 1)
            reason = rng.choice(reasons)

            dataset.append({
                "sample_id": f"s_{len(dataset)+1:05d}",
                "filename": filename,
                "extension": ext,
                "size_bytes": size,
                "age_days": age,
                "reason": reason,
                "label": float(label),
                "category": category
            })

    sample_from_templates(PLAUSIBLE_CACHE_TEMPLATES, n_cache, "plausible_cache", 1.0)
    sample_from_templates(PLAUSIBLE_DUPLICATE_TEMPLATES, n_dup, "plausible_duplicate", 1.0)
    sample_from_templates(PLAUSIBLE_OBSOLETE_TEMPLATES, n_obs, "plausible_obsolete", 1.0)

    sample_from_templates(GAMING_GIBBERISH_TEMPLATES, n_gib, "gaming_gibberish", 0.0)
    sample_from_templates(GAMING_SCORE_FARMING_TEMPLATES, n_farm, "gaming_score_farming", 0.0)
    sample_from_templates(MALICIOUS_SYSTEM_TEMPLATES, n_sys, "malicious_system_risk", 0.0)

    rng.shuffle(dataset)
    return dataset


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate synthetic dataset for Data-to-Dirt AI model.")
    parser.add_argument("--samples", type=int, default=4000, help="Total number of samples (default 4000)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    parser.add_argument("--output", type=str, default="", help="Optional JSON output path")
    args = parser.parse_args()

    data = generate_dataset(num_samples=args.samples, seed=args.seed)
    pos_count = sum(1 for d in data if d["label"] == 1.0)
    neg_count = sum(1 for d in data if d["label"] == 0.0)
    print(f"Generated {len(data)} samples: {pos_count} plausible (1.0), {neg_count} gaming/risk (0.0).")

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        print(f"Saved dataset to {args.output}")
