class CarbonCalculator:
    """Scientific Carbon Calculator for digital storage waste."""

    def __init__(self, profile: Optional[CarbonProfile] = None):
        self.profile = profile or CarbonProfile()

    def set_profile(self, profile: CarbonProfile) -> None:
        """Update active carbon calculation profile."""
        self.profile = profile

    def calculate_energy_kwh(self, size_bytes: float) -> float:
        """Calculate electrical energy required to store data over the projection horizon.

        Args:
            size_bytes: Stored data volume in bytes.

        Returns:
            Energy consumption in kilowatt-hours (kWh).
        """
        if size_bytes < 0:
            raise ValueError(f"size_bytes cannot be negative: {size_bytes}")
        if size_bytes == 0:
            return 0.0

        size_gb = float(size_bytes) / BYTES_PER_GB
        return size_gb * self.profile.kwh_per_gb_year * self.profile.projection_years

    def calculate_carbon_grams(self, size_bytes: float) -> float:
        """Calculate greenhouse gas emissions generated by stored data over projection horizon.

        Args:
            size_bytes: Stored data volume in bytes.

        Returns:
            Emissions in grams of CO2 equivalent (g CO2e).
        """
        energy_kwh = self.calculate_energy_kwh(size_bytes)
        return energy_kwh * self.profile.grid_intensity_gco2_kwh

    def calculate_avoided_offset_kg(self, deleted_bytes: float) -> float:
        """Calculate permanently avoided carbon emissions from permanently eliminating dark data.

        Args:
            deleted_bytes: Volume of purged dark data in bytes.

        Returns:
            Avoided carbon emissions in kilograms of CO2 equivalent (kg CO2e).
        """
        carbon_grams = self.calculate_carbon_grams(deleted_bytes)
        return carbon_grams / 1000.0

    def calculate_tree_equivalent(
        self, deleted_bytes: float, factor: Optional[float] = None
    ) -> float:
        """Translate avoided emissions into fractional annual tree-sequestration equivalents.

        Args:
            deleted_bytes: Volume of purged dark data in bytes.
            factor: Optional tree sequestration factor in kg CO2/tree/year (default: 20.0).

        Returns:
            Equivalent number of trees planted/sequestering for 1 full year.
        """
        tree_factor = factor if factor is not None else self.profile.kg_co2_per_tree_year
        if tree_factor <= 0:
            raise ValueError(f"tree sequestration factor must be positive: {tree_factor}")

        offset_kg = self.calculate_avoided_offset_kg(deleted_bytes)
        return offset_kg / tree_factor

    def calculate_secondary_equivalencies(self, size_bytes: float) -> Dict[str, float]:
        """Compute intuitive real-world equivalents for UI badges and gamification tooltips."""
        carbon_g = self.calculate_carbon_grams(size_bytes)
        return {
            "smartphones_charged": round(carbon_g / SMARTPHONE_CHARGE_CO2_GRAMS, 2),
            "car_km_avoided": round(carbon_g / GASOLINE_CAR_KM_CO2_GRAMS, 4),
            "led_hours_saved": round(carbon_g / LED_BULB_HOUR_CO2_GRAMS, 2),
        }

    def summarize_impact(self, deleted_bytes: float) -> Dict[str, Any]:
        """Produce a comprehensive ecological impact summary dictionary."""
        energy_kwh = self.calculate_energy_kwh(deleted_bytes)
        carbon_g = self.calculate_carbon_grams(deleted_bytes)
        offset_kg = self.calculate_avoided_offset_kg(deleted_bytes)
        trees = self.calculate_tree_equivalent(deleted_bytes)
        secondary = self.calculate_secondary_equivalencies(deleted_bytes)

        return {
            "deleted_bytes": int(deleted_bytes),
            "deleted_gb": round(float(deleted_bytes) / BYTES_PER_GB, 4),
            "energy_kwh": round(energy_kwh, 4),
            "carbon_g": round(carbon_g, 2),
            "offset_kg": round(offset_kg, 4),
            "tree_equivalent": round(trees, 4),
            "millitrees": round(trees * 1000.0, 1),
            "secondary": secondary,
            "profile": {
                "name": self.profile.name,
                "kwh_per_gb_year": self.profile.kwh_per_gb_year,
                "grid_intensity_gco2_kwh": self.profile.grid_intensity_gco2_kwh,
            },
        }


# Default singleton instance for top-level convenience functions
_DEFAULT_CALCULATOR = CarbonCalculator()


def calculate_energy_kwh(size_bytes: float) -> float:
    """Calculate storage energy consumption in kWh using default profile."""
    return _DEFAULT_CALCULATOR.calculate_energy_kwh(size_bytes)


def calculate_carbon_grams(size_bytes: float) -> float:
    """Calculate carbon footprint in grams CO2e using default Singapore profile."""
    return _DEFAULT_CALCULATOR.calculate_carbon_grams(size_bytes)


def calculate_avoided_offset_kg(deleted_bytes: float) -> float:
    """Calculate avoided carbon offset in kg CO2e using default profile."""
    return _DEFAULT_CALCULATOR.calculate_avoided_offset_kg(deleted_bytes)


def calculate_tree_equivalent(deleted_bytes: float, factor: float = DEFAULT_TREE_CO2_KG_YEAR) -> float:
    """Calculate tree-year sequestration equivalents using default profile."""
    return _DEFAULT_CALCULATOR.calculate_tree_equivalent(deleted_bytes, factor=factor)
