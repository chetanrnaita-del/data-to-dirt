"""Data-to-Dirt Scientific Carbon Calculator Engine.

Translates stored data bytes into operational electrical energy (kWh)
and equivalent greenhouse gas emissions (g CO2e) based on empirical
data center storage power models and regional electrical grid intensities.
"""

from dataclasses import dataclass
from typing import Dict, Any, Optional

# Standard Constants
BYTES_PER_GB: float = 1073741824.0  # 1024^3 bytes = 1 GiB
DEFAULT_KWH_PER_GB_YEAR: float = 0.28  # Standard Enterprise cloud storage baseline
DEFAULT_GRID_INTENSITY_SINGAPORE: float = 405.7  # Singapore EMA Grid Emission Factor (g CO2e / kWh)
